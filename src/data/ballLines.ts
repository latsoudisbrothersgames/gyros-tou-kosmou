export function pickBallLine(mood: BallMood, iso2: string, variation = 0): string {
  const seed = [...iso2].reduce((sum, char) => sum + char.charCodeAt(0), 0);
  const lines = BALL_LINES[mood];
  return lines[((seed + Math.trunc(variation)) % lines.length + lines.length) % lines.length];
}

export function countryGreeting(country: Country): string {
  // Το άρθρο υπάρχει ήδη στην αιτιατική· δεν μαντεύουμε γένος από το όνομα.
  const articles: Record<string, string> = { την: 'η', τη: 'η', τον: 'ο', το: 'το', τις: 'οι', τους: 'οι', τα: 'τα' };
  const article = articles[country.nameGreekAccusative.split(' ')[0]];
  return `Γεια! Είμαι ${article ? `${article} ` : ''}${country.nameGreek}`;
}

export function countryFact(country: Country, variation = 0): string {
  const facts = country.factsGreek;
  const index = ((Math.trunc(variation) % facts.length) + facts.length) % facts.length;
  return facts.length ? `Ήξερες ότι… ${facts[index]}` : `Ήξερες ότι… η πρωτεύουσά μου είναι ${country.capitalGreek};`;
}
